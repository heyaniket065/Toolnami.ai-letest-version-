export function buildEnrichedKeywords(tool: {
  slug: string;
  title: string;
  category: string;
  categoryLabel: string;
  keywords: string[];
}): string[] {
  const titleLower = tool.title.toLowerCase();
  const slugWords = tool.slug.replace(/-/g, " ").toLowerCase();
  const extra = EXTRA_TOOL_KEYWORDS[tool.slug] ?? [];

  const generated = [
    ...tool.keywords,
    ...extra,
    titleLower,
    slugWords,
    `${titleLower} online`,
    `free ${titleLower}`,
    `${titleLower} free online`,
    `${slugWords} tool`,
    `${titleLower} toolnami`,
    `${tool.categoryLabel.toLowerCase()} online`,
    "free online tool no signup",
  ];

  const seen = new Set<string>();
  const unique: string[] = [];
  for (const kw of generated) {
    const normalized = kw.trim().toLowerCase();
    if (normalized && !seen.has(normalized)) {
      seen.add(normalized);
      unique.push(kw.trim());
    }
  }
  return unique;
}
